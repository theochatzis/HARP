"""HTCondor submission of HARP jobs.

One job = one invocation of ``harp run <cfg> inputFiles=<chunk> ...`` on a
chunk of files of one sample. The work directory (submit file, job lists,
logs) is created outside EOS (condor cannot read submit files from EOS); the
code is shipped as a tarball so the worker does not need the repository.
Outputs are copied to the output directory with xrdcp (EOS) or cp.

Layout of a work directory  ~/condor_work/HARP/<tag>/:
    harp.tar.gz      build/bin, build/lib, python, configs, samples, env
    job.sh           worker script
    job.sub          submit file
    jobs/job_<i>.txt input file list per job
    jobs.json        job index: id -> sample, files, expected output
    logs/            condor logs
"""
import json
import os
import shlex
import subprocess
import sys
import tarfile
from collections import OrderedDict

from harp import samples

HARP_BASE = samples.HARP_BASE


def default_work_dir(tag):
    home = os.path.expanduser("~")
    base = home if not home.startswith("/eos/") else "/tmp/%s" % os.environ.get("USER", "user")
    return os.path.join(base, "condor_work", "HARP", tag)


def to_xrootd(path):
    if path.startswith("/eos/"):
        return "root://eosuser.cern.ch/" + path
    return path


def chunks(items, n):
    for i in range(0, len(items), n):
        yield items[i:i + n]


def make_tarball(path):
    build = os.environ.get("HARP_BUILD", os.path.join(HARP_BASE, "build"))
    with tarfile.open(path, "w:gz") as tar:
        for rel, src in [("build/bin", os.path.join(build, "bin")), ("build/lib", os.path.join(build, "lib")),
                         ("python", os.path.join(HARP_BASE, "python")), ("configs", os.path.join(HARP_BASE, "configs")),
                         ("samples", os.path.join(HARP_BASE, "samples")), ("env", os.path.join(HARP_BASE, "env")),
                         ("scripts", os.path.join(HARP_BASE, "scripts"))]:
            if not os.path.exists(src):
                raise RuntimeError("missing %s (did you build?)" % src)
            tar.add(src, arcname=os.path.join("HARP", rel), filter=lambda ti: None if "__pycache__" in ti.name else ti)
    return path


JOB_SH = r"""#!/bin/bash
# HARP condor worker script (generated by harp submit). Arguments: <job id>
set -eo pipefail
JOBID="$1"
echo "[job] start $(date) on $(hostname) jobid=$JOBID"
WORK="$PWD"
tar -xzf harp.tar.gz
export HARP_ENV={harp_env}
source HARP/env/setup.sh      # LCG setup scripts are not 'set -u' clean, hence no -u above
cd "$WORK"
INPUTS="$(python3 -c "import json,sys; j=json.load(open('jobs.json'))[sys.argv[1]]; print(','.join(j['files']))" "$JOBID")"
OUTNAME="$(python3 -c "import json,sys; j=json.load(open('jobs.json'))[sys.argv[1]]; print(j['output'])" "$JOBID")"
HISTNAME="$(python3 -c "import json,sys; j=json.load(open('jobs.json'))[sys.argv[1]]; print(j['hist'])" "$JOBID")"
echo "[job] inputs: $INPUTS"
harp run "HARP/configs/{cfg}" inputFiles="$INPUTS" {opts} {output_opt}="$OUTNAME" {hist_opt}="$HISTNAME" --workdir "$WORK/work_$JOBID"
for f in "$OUTNAME" "$HISTNAME"; do
  [ -f "$f" ] || continue
  if [[ "{outdir}" == root://* ]]; then xrdcp -f "$f" "{outdir}/$f"; else mkdir -p "{outdir}"; cp -f "$f" "{outdir}/$f"; fi
  echo "[job] copied $f -> {outdir}/$f"
done
echo "[job] done $(date)"
"""

JOB_SUB = """universe              = vanilla
executable            = {work}/job.sh
arguments             = $(jobid)
transfer_input_files  = {work}/harp.tar.gz, {work}/jobs.json
should_transfer_files = YES
when_to_transfer_output = ON_EXIT
output                = {work}/logs/job_$(jobid).out
error                 = {work}/logs/job_$(jobid).err
log                   = {work}/logs/cluster.log
request_cpus          = 1
request_memory        = {memory}
+JobFlavour           = "{flavour}"
getenv                = False
max_retries           = 2
queue jobid from {work}/{joblist}
"""


def prepare(cfg, sample_names, output_dir, tag, files_per_job=10, max_files=-1, options=(), work_dir=None,
            flavour="workday", memory="2500MB", skim=True):
    """Create the work directory. Returns (work_dir, jobs dict)."""
    # compare real paths: /eos/home-t/... and /eos/user/t/... are the same directory
    cfg_rel = os.path.relpath(os.path.realpath(cfg), os.path.realpath(os.path.join(HARP_BASE, "configs")))
    if cfg_rel.startswith(".."):
        raise RuntimeError("the configuration must live under %s/configs to be shipped with the tarball" % HARP_BASE)
    cfg_stem = os.path.splitext(os.path.basename(cfg))[0].replace("_cfg", "")
    work = work_dir or default_work_dir(tag)
    if "/eos/" in work:
        raise RuntimeError("work directory must not be on EOS: %s" % work)
    os.makedirs(os.path.join(work, "logs"), exist_ok=True)
    os.makedirs(os.path.join(work, "jobs"), exist_ok=True)

    jobs = OrderedDict()
    for name in sample_names:
        files = samples.files(name, max_files=max_files)
        for i, chunk in enumerate(chunks(files, files_per_job)):
            jid = "%s_%s_%03d" % (name, cfg_stem, i)
            jobs[jid] = OrderedDict(sample=name, files=chunk,
                                    output="%s_%s_%03d.root" % (name, cfg_stem, i),
                                    hist="%s_%s_hists_%03d.root" % (name, cfg_stem, i))
    with open(os.path.join(work, "jobs.json"), "w") as f:
        json.dump(jobs, f, indent=1)
    with open(os.path.join(work, "jobs.txt"), "w") as f:
        f.write("\n".join(jobs) + "\n")

    make_tarball(os.path.join(work, "harp.tar.gz"))
    outdir = to_xrootd(output_dir.rstrip("/"))
    job_sh = JOB_SH.format(cfg=cfg_rel, opts=" ".join(shlex.quote(o) for o in options), outdir=outdir,
                           harp_env=os.environ.get("HARP_ENV", "lcg"),
                           output_opt="outputFile", hist_opt="histFile")
    if not skim:  # hist-only configurations have no outputFile option
        job_sh = job_sh.replace(' outputFile="$OUTNAME"', "")
    with open(os.path.join(work, "job.sh"), "w") as f:
        f.write(job_sh)
    os.chmod(os.path.join(work, "job.sh"), 0o755)
    with open(os.path.join(work, "job.sub"), "w") as f:
        f.write(JOB_SUB.format(work=work, flavour=flavour, memory=memory, joblist="jobs.txt"))
    meta = OrderedDict(cfg=cfg_rel, samples=list(sample_names), output_dir=output_dir, tag=tag, files_per_job=files_per_job,
                       options=list(options), skim=skim, n_jobs=len(jobs))
    with open(os.path.join(work, "meta.json"), "w") as f:
        json.dump(meta, f, indent=1)
    return work, jobs


def submit(work, joblist="jobs.txt", dry_run=False):
    sub = os.path.join(work, "job.sub")
    if joblist != "jobs.txt":
        with open(sub) as f:
            text = f.read().replace("queue jobid from %s/jobs.txt" % work, "queue jobid from %s/%s" % (work, joblist))
        sub = os.path.join(work, "job_resubmit.sub")
        with open(sub, "w") as f:
            f.write(text)
    cmd = ["condor_submit", sub]
    print("[harp submit] " + " ".join(cmd))
    if dry_run:
        return 0
    env = {k: v for k, v in os.environ.items() if "/eos/" not in v or k in ("HOME",)}
    env["HOME"] = os.path.expanduser("~")
    return subprocess.call(cmd, env=env, cwd=work)


def check(work, verbose=True):
    """Open every expected output and report good / bad jobs. Writes resubmit.txt."""
    import ROOT  # noqa: lazy import, needs the LCG environment
    ROOT.gErrorIgnoreLevel = ROOT.kError
    with open(os.path.join(work, "meta.json")) as f:
        meta = json.load(f)
    with open(os.path.join(work, "jobs.json")) as f:
        jobs = json.load(f)
    outdir = meta["output_dir"]
    good, bad = [], []
    for jid, j in jobs.items():
        ok = True
        expected = [j["hist"]] + ([j["output"]] if meta.get("skim", True) else [])
        for fn in expected:
            path = os.path.join(outdir, fn)
            if not os.path.exists(path):
                ok = False
                if verbose:
                    print("  missing %s" % path)
                continue
            f = ROOT.TFile.Open(path)
            if not f or f.IsZombie() or f.TestBit(ROOT.TFile.kRecovered):
                ok = False
                if verbose:
                    print("  corrupted %s" % path)
            elif fn == j["hist"] and not f.Get("harp/cutflow"):
                ok = False
                if verbose:
                    print("  no cutflow in %s" % path)
            if f:
                f.Close()
        (good if ok else bad).append(jid)
    with open(os.path.join(work, "resubmit.txt"), "w") as f:
        f.write("\n".join(bad) + ("\n" if bad else ""))
    print("[harp check] %d good, %d bad job(s)%s" % (len(good), len(bad), "; resubmit with: harp submit --resubmit --tag %s" % meta["tag"] if bad else ""))
    return good, bad


def merge(work, dest=None):
    """hadd the hist (and skim) outputs per sample into <output_dir>/merged/<sample>.root."""
    with open(os.path.join(work, "meta.json")) as f:
        meta = json.load(f)
    with open(os.path.join(work, "jobs.json")) as f:
        jobs = json.load(f)
    outdir = meta["output_dir"]
    dest = dest or os.path.join(outdir, "merged")
    os.makedirs(dest, exist_ok=True)
    rc = 0
    for sample in meta["samples"]:
        for key, suffix in [("hist", ""), ("output", "_skim")]:
            if key == "output" and not meta.get("skim", True):
                continue
            inputs = [os.path.join(outdir, j[key]) for jid, j in jobs.items() if j["sample"] == sample]
            inputs = [p for p in inputs if os.path.exists(p)]
            if not inputs:
                print("[harp merge] nothing to merge for %s (%s)" % (sample, key))
                continue
            target = os.path.join(dest, "%s%s.root" % (sample, suffix))
            cmd = ["hadd", "-f", target] + inputs
            print("[harp merge] %s <- %d file(s)" % (target, len(inputs)))
            rc |= subprocess.call(cmd, stdout=subprocess.DEVNULL)
    return rc
